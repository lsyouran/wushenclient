import { defineNpc } from '@engine/world/define.js';

/**
 * 木人桩 —— **可打死的练功靶子**，也是"打怪 → 经验/潜能"这条闭环的样板。
 *
 * 对照 wushen `world/npc/pub/muren.js`，但**有一处刻意的不同**（见下）。
 *
 * ★★ wushen 那只木人是**打不死的**：它把 `die()` 整个覆写成"回满血 + 播报一句
 *   `$N身上破损的木头剥落，再次神采奕奕`"，永远 `return false`。用途只有一个：
 *   测伤害。于是它的 `exp/pot` 即使写了也永远发不出去 —— 这正是 wushen 里
 *   "打怪给经验"长期没有真正接上的一个缩影（`add_exp` 的调用点全在副本结算与
 *   采集/钓鱼那类动作里，`npc.js` 的 `die()` 一处都没有）。
 *
 * ★ 本项目要的是**成长闭环**，所以做成**正常会死**的靶子：
 *   - 血薄（`con: 8` ⇒ 派生上限几十点），新手两三下就能打倒；
 *   - 打死给 `exp` / `pot`（数值口径照 wushen 副本小怪的 500 档，经验略高）；
 *   - 死了不掉落（`drops` 不写）—— 它是练功桩，不是宝箱；
 *   - 30 秒后原地重生（`respawn_ms`），于是"打怪 → 练技能 → 再打"可以反复跑。
 *
 * ★ 数值全部写在这个 def 里：想调收益就改这里，引擎侧不需要动
 *   （`Npc.afterDeath` 只负责"把 def 上的数交给击杀者"）。
 */
defineNpc('pub/muren', {
  name: '木人桩',
  desc: '一具用硬木扎成的假人，身上缠着麻绳，专门给人练拳脚用的。',
  gender: 0,
  age: 5,
  per: 10,
  con: 8,
  dex: 5,
  int: 1,
  str: 5,
  hp: 40,
  mp: 0,
  max_mp: 0,
  // ★ 击杀奖励（不是它自己的经验 —— 见 `NpcDef.exp` 的说明）
  exp: 1000,
  pot: 500,
  // ★ 练功桩的节奏：**5 秒一刷**（2026-10-19 从 30 秒调下来）。
  //   调它的理由不是"更好玩"，是**测试成长曲线**：一次调系数要连着打几十只木人，
  //   30 秒一刷会让"验证一次数值改动"变成十分钟的等待。
  //   ★ 代价要说清：5 秒一刷 + 每只 1000 经验 ⇒ 这是**测试期的收益率**，
  //     正式内容上来以后必须打回 30 秒档（或让木人只给一次收益）。
  respawn_ms: 5_000,
});
